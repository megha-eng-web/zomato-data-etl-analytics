SELECT *
FROM ZOMATO_PROJECT.RAW.ZOMATO_CLEAN
LIMIT 10;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT RESTAURANT_NAME || '|' || LOCATION) AS UNIQUE_RESTAURANT_LOCATIONS
FROM ZOMATO_PROJECT.RAW.ZOMATO_CLEAN;

CREATE OR REPLACE TABLE ZOMATO_PROJECT.RAW.ZOMATO_RESTAURANT AS
SELECT *
FROM ZOMATO_PROJECT.RAW.ZOMATO_CLEAN
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RESTAURANT_NAME, LOCATION
    ORDER BY VOTES DESC
) = 1;
SELECT COUNT(*) AS UNIQUE_RESTAURANTS
FROM ZOMATO_PROJECT.RAW.ZOMATO_RESTAURANT;

SELECT
    COUNT(*) AS TOTAL_RESTAURANTS,
    COUNT(DISTINCT RESTAURANT_NAME) AS UNIQUE_NAMES,
    COUNT(DISTINCT LOCATION) AS UNIQUE_LOCATIONS
FROM ZOMATO_PROJECT.RAW.ZOMATO_RESTAURANT;

SELECT
    RESTAURANT_NAME,
    LOCATION,
    COUNT(*) AS CNT
FROM ZOMATO_PROJECT.RAW.ZOMATO_RESTAURANT
GROUP BY RESTAURANT_NAME, LOCATION
HAVING COUNT(*) > 1
ORDER BY CNT DESC;

