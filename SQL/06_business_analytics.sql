// Analytics Use Case 1: Top-Rated Restaurants
SELECT
    DR.RESTAURANT_NAME,
    DL.LOCATION,
    DC.CUISINES,
    FR.RATING,
    FR.VOTES,
    FR.APPROX_COST
FROM FACT_RESTAURANT FR
JOIN DIM_RESTAURANT DR
    ON FR.RESTAURANT_ID = DR.RESTAURANT_ID
LEFT JOIN DIM_LOCATION DL
    ON FR.LOCATION_ID = DL.LOCATION_ID
LEFT JOIN DIM_CUISINE DC
    ON FR.CUISINE_ID = DC.CUISINE_ID
WHERE FR.RATING IS NOT NULL
ORDER BY FR.RATING DESC, FR.VOTES DESC
LIMIT 20;


//Analytics Use Case 2: Best Restaurants Under ₹500
SELECT
    DR.RESTAURANT_NAME,
    DL.LOCATION,
    DC.CUISINES,
    FR.RATING,
    FR.VOTES,
    FR.APPROX_COST
FROM FACT_RESTAURANT FR
JOIN DIM_RESTAURANT DR
    ON FR.RESTAURANT_ID = DR.RESTAURANT_ID
LEFT JOIN DIM_LOCATION DL
    ON FR.LOCATION_ID = DL.LOCATION_ID
LEFT JOIN DIM_CUISINE DC
    ON FR.CUISINE_ID = DC.CUISINE_ID
WHERE FR.APPROX_COST <= 500
  AND FR.RATING IS NOT NULL
ORDER BY FR.RATING DESC, FR.VOTES DESC
LIMIT 20;

//Analytics Use Case 3: Online Order vs Table Booking

SELECT
    ONLINE_ORDER,
    BOOK_TABLE,
    COUNT(*) AS RESTAURANT_COUNT
FROM FACT_RESTAURANT
GROUP BY
    ONLINE_ORDER,
    BOOK_TABLE
ORDER BY RESTAURANT_COUNT DESC;

//Analytics Use Case 4: Restaurant Count by Location

