INSERT INTO FACT_RESTAURANT (
    RESTAURANT_ID,
    LOCATION_ID,
    CUISINE_ID,
    TYPE_ID,
    ONLINE_ORDER,
    BOOK_TABLE,
    RATING,
    VOTES,
    APPROX_COST
)
SELECT
    DR.RESTAURANT_ID,
    DL.LOCATION_ID,
    DC.CUISINE_ID,
    DT.TYPE_ID,

    Z.ONLINE_ORDER,
    Z.BOOK_TABLE,
    Z.RATING,
    Z.VOTES,
    Z.APPROX_COST

FROM ZOMATO_CLEAN Z

LEFT JOIN DIM_RESTAURANT DR
    ON TRIM(Z.URL) = DR.URL

LEFT JOIN DIM_LOCATION DL
    ON COALESCE(TRIM(Z.LOCATION), '') =
       COALESCE(DL.LOCATION, '')
   AND COALESCE(TRIM(Z.LISTED_IN_CITY), '') =
       COALESCE(DL.LISTED_IN_CITY, '')

LEFT JOIN DIM_CUISINE DC
    ON COALESCE(TRIM(Z.DISH_LIKED), '') =
       COALESCE(DC.DISH_LIKED, '')
   AND COALESCE(TRIM(Z.CUISINES), '') =
       COALESCE(DC.CUISINES, '')

LEFT JOIN DIM_TYPE DT
    ON COALESCE(TRIM(Z.REST_TYPE), '') =
       COALESCE(DT.REST_TYPE, '')
   AND COALESCE(TRIM(Z.LISTED_IN_TYPE), '') =
       COALESCE(DT.LISTED_IN_TYPE, '');

       SELECT COUNT(*) AS FACT_ROWS
FROM FACT_RESTAURANT;

