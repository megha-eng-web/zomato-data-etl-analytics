    COUNT(*) AS TOTAL_RESTAURANTS,
    ROUND(AVG(f.RATING), 2) AS AVG_RATING,
    ROUND(AVG(f.VOTES), 0) AS AVG_VOTES,
    ROUND(AVG(f.APPROX_COST), 2) AS AVG_APPROX_COST
