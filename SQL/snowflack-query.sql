    COUNT_IF(RATING IS NOT NULL) AS RATING_FILLED,
    COUNT_IF(VOTES IS NOT NULL) AS VOTES_FILLED,
    COUNT_IF(APPROX_COST IS NOT NULL) AS COST_FILLED
FROM ZOMATO_CLEAN;


