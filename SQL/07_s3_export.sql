-- 07_s3_export.sql
-- Zomato Data ETL & Analytics Pipeline
-- ============================================================
-- Purpose:
--   Export cleaned data, dimension tables and the fact table from
--   Snowflake back to AWS S3 as CSV files.
-- ============================================================

LIST @ZOMATO_PROJECT.RAW.MANAGE_STAGE;

COPY INTO @ZOMATO_PROJECT.RAW.MANAGE_STAGE/exports/zomato_clean
FROM ZOMATO_PROJECT.RAW.ZOMATO_CLEAN
FILE_FORMAT = (
    TYPE = CSV
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
HEADER = TRUE
OVERWRITE = TRUE;

LIST @ZOMATO_PROJECT.RAW.MANAGE_STAGE/exports;


COPY INTO @ZOMATO_PROJECT.RAW.MANAGE_STAGE/exports/dim_restaurant
FROM ZOMATO_PROJECT.RAW.DIM_RESTAURANT
FILE_FORMAT = (
    TYPE = CSV
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
HEADER = TRUE
OVERWRITE = TRUE;


COPY INTO @ZOMATO_PROJECT.RAW.MANAGE_STAGE/exports/dim_location
FROM ZOMATO_PROJECT.RAW.DIM_LOCATION
FILE_FORMAT = (
    TYPE = CSV
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
HEADER = TRUE
OVERWRITE = TRUE;

COPY INTO @ZOMATO_PROJECT.RAW.MANAGE_STAGE/exports/dim_cuisine
