    DR.RESTAURANT_NAME,
    DL.LOCATION,
    DC.CUISINES,
    FR.RATING,
    FR.VOTES,
    FR.APPROX_COST
FROM ZOMATO_PROJECT.RAW.FACT_RESTAURANT FR
