CREATE OR REPLACE VIEW ZOMATO_PROJECT.ANALYTICS.VW_VOTE_ANALYSIS AS
SELECT
    CASE
        WHEN f.VOTES = 0 THEN 'No Votes'
        WHEN f.VOTES < 100 THEN 'Low Votes'
        WHEN f.VOTES < 500 THEN 'Medium Votes'
        WHEN f.VOTES < 1000 THEN 'High Votes'
        ELSE 'Very High Votes'
    END AS VOTE_CATEGORY,
    COUNT(*) AS RESTAURANT_COUNT,
    ROUND(AVG(f.RATING), 2) AS AVG_RATING,
    ROUND(AVG(f.APPROX_COST), 2) AS AVG_COST,
    SUM(f.VOTES) AS TOTAL_VOTES
FROM ZOMATO_PROJECT.RAW.FACT_RESTAURANT f
GROUP BY
    CASE
        WHEN f.VOTES = 0 THEN 'No Votes'
        WHEN f.VOTES < 100 THEN 'Low Votes'
        WHEN f.VOTES < 500 THEN 'Medium Votes'
        WHEN f.VOTES < 1000 THEN 'High Votes'
        ELSE 'Very High Votes'
    END
ORDER BY TOTAL_VOTES DESC;

