    URL,
    TRIM(ADDRESS) AS ADDRESS,
    TRIM(NAME) AS RESTAURANT_NAME,

    CASE
        WHEN LOWER(TRIM(ONLINE_ORDER)) = 'yes' THEN TRUE
        WHEN LOWER(TRIM(ONLINE_ORDER)) = 'no' THEN FALSE
        ELSE NULL
    END AS ONLINE_ORDER,

    CASE
        WHEN LOWER(TRIM(BOOK_TABLE)) = 'yes' THEN TRUE
        WHEN LOWER(TRIM(BOOK_TABLE)) = 'no' THEN FALSE
        ELSE NULL
    END AS BOOK_TABLE,

    CASE
        WHEN TRIM(RATE) = '' OR UPPER(TRIM(RATE)) = 'NEW' THEN NULL
        ELSE TRY_TO_DECIMAL(
            REGEXP_SUBSTR(
                TRIM(RATE),
                '[0-9]+(\.[0-9]+)?'
            ),
            3,
            1
        )
    END AS RATING,

    TRY_TO_NUMBER(
        REPLACE(TRIM(VOTES), ',', '')
    ) AS VOTES,

    TRIM(PHONE) AS PHONE,
    TRIM(LOCATION) AS LOCATION,
    TRIM(REST_TYPE) AS REST_TYPE,
    TRIM(DISH_LIKED) AS DISH_LIKED,
    TRIM(CUISINES) AS CUISINES,

    TRY_TO_NUMBER(
        REPLACE(TRIM(APPROX_COST), ',', '')
    ) AS APPROX_COST,

    REVIEWS_LIST,
    MENU_ITEM,
    TRIM(LISTED_IN_TYPE) AS LISTED_IN_TYPE,
    TRIM(LISTED_IN_CITY) AS LISTED_IN_CITY

FROM STAGE_RAW_DATA;

-- Basic validation after transformation
