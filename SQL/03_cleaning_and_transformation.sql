    COUNT(*) AS TOTAL_ROWS,
    COUNT(RATING) AS RATING_FILLED,
    COUNT(VOTES) AS VOTES_FILLED,
    COUNT(APPROX_COST) AS COST_FILLED,
    COUNT(CUISINES) AS CUISINES_FILLED
FROM ZOMATO_CLEAN;

